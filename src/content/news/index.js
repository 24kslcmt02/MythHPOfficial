/** 日付の新しい順に並べた一覧 */
export function sortedNews() {
  return [...news].sort((a, b) => (a.date < b.date ? 1 : -1));
}

/** slug から記事を取得する */
export function findNews(slug) {
  return news.find((entry) => entry.slug === slug) ?? null;
}
